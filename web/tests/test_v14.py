from pathlib import Path
from playwright.sync_api import sync_playwright
import json
ROOT=Path(__file__).resolve().parent.parent
OUT=ROOT/'screenshots'
OUT.mkdir(exist_ok=True)
checks=[]
def ck(condition,message):
    checks.append({'name':message,'passed':bool(condition)})
    print(('PASS' if condition else 'FAIL'), message)
def attr(page,selector,field='opacity'):
    return page.locator(selector).first.evaluate('(el,p)=>getComputedStyle(el).getPropertyValue(p)',field)
with sync_playwright() as p:
    browser=p.chromium.launch(headless=True,executable_path='/usr/bin/chromium',args=['--no-sandbox','--disable-dev-shm-usage'])
    page=browser.new_page(viewport={'width':800,'height':480},device_scale_factor=1)
    errors=[]
    page.on('pageerror',lambda err:errors.append(str(err)))
    page.set_content((ROOT/'NORDVENT_Standalone.html').read_text(),wait_until='domcontentloaded',timeout=120000)
    page.wait_for_timeout(450)
    ck(page.locator('#healthChip').is_visible(),'Persistent system health status visible')
    ck(page.locator('#healthChipText').inner_text()=='Systems OK','No alerts at startup')
    ck(page.locator('#buildingImage').get_attribute('src').startswith('data:image/webp'),'House animation embedded')
    ck(page.locator('#waterFx').count()==1,'Blue independent water circuit available')
    ck(page.locator('#defrostFx').count()==1,'Defrost artwork available')
    ck(page.locator('#headerAlarm').is_visible() and page.locator('#headerLock').is_visible(),'Floating security controls visible')
    ck(page.locator('#fixture-living_ceiling').evaluate('e=>+getComputedStyle(e).opacity')>.9,'Living lights default ON')
    ck(page.locator('#fixture-kitchen_pendants').evaluate('e=>+getComputedStyle(e).opacity')>.9,'Kitchen lights default ON')
    page.screenshot(path=str(OUT/'v14_home.png'))
    page.locator('[data-page="climate"]').click()
    ck(page.locator('#workspace').get_attribute('data-flow')=='eco','Eco airflow state active')
    eco_width=float(attr(page,'.air-moving','stroke-width').replace('px','') or 0)
    page.screenshot(path=str(OUT/'v14_eco.png'))
    page.locator('.vent-modes [data-mode="Auto"]').click()
    ck(page.locator('#workspace').get_attribute('data-flow')=='auto','Auto airflow state active')
    auto_width=float(attr(page,'.air-moving','stroke-width').replace('px','') or 0)
    ck(auto_width>eco_width,'Auto flow has denser/brighter line than Eco')
    page.locator('.vent-modes [data-mode="Manual"]').click()
    ck(page.locator('.manual-v13 input').is_visible(),'Manual has a hidden-until-needed slider')
    page.locator('.manual-v13 input').fill('280')
    ck('280' in page.locator('#manualReadout').inner_text(),'Manual slider updates flow readout')
    page.locator('[data-action="boost"]').click()
    ck(page.locator('#workspace').get_attribute('data-flow')=='boost','Boost uses separate effect state')
    ck(page.locator('#airFx').get_attribute('class').find('boost-surge')>=0,'Boost triggers short surge')
    page.screenshot(path=str(OUT/'v14_boost.png'))
    page.locator('[data-action="boost"]').click()
    page.locator('[data-page="energy"]').click()
    ck(page.locator('#waterFx').get_attribute('class').find('on')>=0,'Hot-water circuit on while available')
    page.screenshot(path=str(OUT/'v14_energy.png'))
    page.locator('[data-action="toggleWater"]').click()
    ck('on' not in page.locator('#waterFx').get_attribute('class').split(),'Hot-water FX off independently')
    page.locator('[data-action="toggleWater"]').click()
    page.locator('[data-action="waterValveConfirm"]').click()
    ck(page.locator('#modalBack').is_visible(),'Valve shutoff confirmation')
    page.locator('#dialogYes').click()
    ck('on' not in page.locator('#waterFx').get_attribute('class').split(),'Closing valve stops hot-water FX')
    # Reopen
    page.locator('[data-action="waterValveConfirm"]').click()
    page.locator('#dialogYes').click()
    page.locator('[data-page="more"]').click()
    page.locator('[data-tab="demo"]').click()
    ck(page.locator('.demo-chip').count()==10,'Ten compact demo scenario controls available')
    page.locator('[data-action="leakTest"]').click()
    ck(page.locator('#healthChip').get_attribute('data-level')=='critical','Leak causes critical health state')
    ck(page.locator('#fault-leak').get_attribute('class').find('active')>=0,'Leak appears at utility location')
    page.screenshot(path=str(OUT/'v14_leak.png'))
    page.locator('#healthChip').click()
    ck(page.locator('.health-dialog-row').count()>=1,'Health dialog lists faults')
    ck(page.locator('[data-action="waterValveConfirm"]').count()>=1,'Leak dialog offers shutoff')
    page.locator('.health-dialog-buttons [data-action="waterValveConfirm"]').click()
    page.locator('#dialogYes').click()
    ck(page.locator('#waterFx').get_attribute('class').find('on')<0,'Water FX stops after leak shutoff')
    # smoke
    page.locator('#modalBack [data-action="dismiss"]').last.click()
    page.locator('[data-tab="demo"]').click()
    page.locator('[data-action="smokeTest"]').click()
    ck(page.locator('#fault-smoke').get_attribute('class').find('active')>=0,'Smoke/CO marker in kitchen')
    # IAQ auto override: first restore valve and fault conditions, switch eco
    page.locator('.demo-reset[data-action="clearFaults"]').click()
    page.locator('[data-page="climate"]').click()
    page.locator('.vent-modes [data-mode="Eco"]').click()
    page.locator('[data-page="more"]').click()
    page.locator('[data-tab="demo"]').click()
    page.locator('[data-action="airTest"]').click()
    ck(page.locator('#workspace').get_attribute('data-flow')=='iaq','High CO2 automatically changes airflow effect')
    page.locator('[data-page="climate"]').click()
    ck('280' in page.locator('.measure-hero').inner_text(),'IAQ automation raises airflow to 280 m3/h')
    page.locator('[data-action="toggleIaq"]').click()
    ck(page.locator('#workspace').get_attribute('data-flow')=='eco','Disabling IAQ auto restores user Eco mode')
    page.locator('[data-page="more"]').click()
    page.locator('[data-tab="demo"]').click()
    page.locator('.demo-reset[data-action="clearFaults"]').click()
    page.locator('[data-action="defrostTest"]').click()
    ck(page.locator('#defrostFx').get_attribute('class').find('on')>=0,'Heat pump defrost visual activates')
    page.locator('[data-action="filterTest"]').click()
    page.locator('[data-action="frostTest"]').click()
    page.locator('[data-action="windowTest"]').click()
    page.locator('[data-action="sensorTest"]').click()
    page.locator('[data-tab="health"]').click()
    ck(page.locator('.health-data').inner_text().find('Stale')>=0,'Offline sensor represented as stale')
    page.screenshot(path=str(OUT/'v14_health.png'))
    # verify all page layout with visible buttons
    for tab in ['home','rooms','climate','energy','routines','more']:
        page.locator(f'[data-page="{tab}"]').click()
        ck(page.locator('#workspace').get_attribute('data-page')==tab,f'{tab.title()} renders')
        ck(page.evaluate('document.documentElement.scrollHeight <= 481 && document.documentElement.scrollWidth <=801'),f'{tab.title()} has no scroll')
    page.locator('[data-page="rooms"]').click()
    page.locator('.room-pick[data-room="bedroom"]').click()
    page.locator('[data-action="nextRoom"]').click()
    ck(page.locator('.room-heading-row h2').inner_text()=='Living Room','Direct room switching preserved')
    page.locator('nav [data-page="home"]').click()
    page.locator('.mode-choice[data-scene="Night"]').click()
    page.locator('[data-action="applyScene"]').click()
    ck(page.locator('#modeSceneHint').inner_text()=='NIGHT · SOFT LIGHTING','Night differentiated')
    page.locator('.mode-choice[data-scene="Away"]').click()
    page.locator('[data-action="applyScene"]').click()
    ck(page.locator('#modeSceneHint').inner_text()=='AWAY · LIGHTS OFF','Away differentiated')
    page.locator('#headerAlarm').click()
    page.locator('#dialogYes').click()
    ck('Armed' in page.locator('#headerAlarm').inner_text(),'Alarm state confirmation preserved')
    ck(page.locator('#headerAlarm').get_attribute('class').find('state-confirm')>=0,'Security confirmation FX applied')
    ck(not errors, 'No uncaught JS errors: '+repr(errors))
    browser.close()
(OUT/'v14_checks.json').write_text(json.dumps(checks,indent=2))
print('RESULT',sum(x['passed'] for x in checks),'/',len(checks))
if not all(x['passed'] for x in checks):raise SystemExit(1)
