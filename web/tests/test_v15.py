"""NORDVENT v15: full UX and regression checks on the self-contained 800x480 preview."""
from pathlib import Path
from playwright.sync_api import sync_playwright
import json
root=Path(__file__).resolve().parent.parent
out=root/'screenshots';out.mkdir(exist_ok=True)
checks=[]
def check(cond,msg):
    checks.append({'name':msg,'passed':bool(cond)})
    print(('PASS' if cond else 'FAIL'),msg)

def outside(a,b):
    return a['x']+a['width']<=b['x'] or b['x']+b['width']<=a['x'] or a['y']+a['height']<=b['y'] or b['y']+b['height']<=a['y']
with sync_playwright() as p:
  browser=p.chromium.launch(headless=True, executable_path='/usr/bin/chromium', args=['--no-sandbox','--disable-dev-shm-usage'])
  page=browser.new_page(viewport={'width':800,'height':480},device_scale_factor=1)
  errors=[]
  page.on('pageerror',lambda e:errors.append(str(e)))
  page.set_content((root/'NORDVENT_Standalone.html').read_text(),wait_until='domcontentloaded',timeout=120000)
  page.wait_for_timeout(350)
  check(page.locator('#healthChip').is_visible(),'Global system-health chip visible')
  check(page.locator('#healthChipText').inner_text()=='Systems OK','Health OK on startup')
  check(page.locator('#buildingImage').get_attribute('src').startswith('data:image/webp'),'Animated background bundled offline')
  check(page.locator('#headerAlarm').is_visible() and page.locator('#headerLock').is_visible(),'Alarm and lock remain over the building')
  check(page.locator('#fixture-living_ceiling').evaluate('e=>+getComputedStyle(e).opacity')>.9,'Living light is on by default')
  page.locator('nav [data-page="climate"]').click()
  check(page.locator('.v15-hud').is_visible(),'Airflow moved to house')
  check(page.locator('#overlayFlowReadout').inner_text()=='110','Eco airflow shown in house overlay')
  check(page.locator('.climate-v15 .measure-hero').count()==0,'No redundant large number in left dock')
  check(page.locator('.v15-hud-modes button').count()==3,'Eco/Auto/Manual selector located on house')
  check(page.locator('.climate-v15 .v15-control-switch').count()==3,'Three large side controls')
  check(all(btn.bounding_box()['height']>=43 for btn in page.locator('.climate-v15 .v15-control-switch').all()),'Side switches have 43px touch targets')
  check(all(btn.bounding_box()['height']>=43 for btn in page.locator('.v15-hud-modes button').all()),'Mode selector has 43px touch targets')
  check(outside(page.locator('.v15-hud').bounding_box(),page.locator('#headerLock').bounding_box()),'Climate HUD avoids lock')
  check(outside(page.locator('.v15-hud').bounding_box(),page.locator('#headerAlarm').bounding_box()),'Climate HUD avoids alarm')
  check(outside(page.locator('.v15-hud').bounding_box(),page.locator('#healthChip').bounding_box()),'Climate HUD avoids system-health chip')
  check(outside(page.locator('.v15-hud').bounding_box(),page.locator('.climate-v15').bounding_box()),'Climate HUD avoids control dock')
  page.screenshot(path=str(out/'v15_climate.png'))
  page.locator('.v15-hud-modes [data-mode="Auto"]').click()
  check(page.locator('#overlayFlowReadout').inner_text()=='215','Auto airflow updates house overlay')
  check(page.locator('#workspace').get_attribute('data-flow')=='auto','Auto FX active')
  page.locator('.v15-hud-modes [data-mode="Manual"]').click()
  check(page.locator('.v15-manual-control input').is_visible(),'Manual reveals slider in dock only when needed')
  check(page.locator('.v15-hud-modes [data-mode="Manual"]').get_attribute('aria-pressed')=='true','Manual selected visually')
  page.locator('.v15-manual-control input').fill('280')
  check(page.locator('#overlayFlowReadout').inner_text()=='280','Manual input changes house flow immediately')
  check('280' in page.locator('#manualReadout').inner_text(),'Manual control readout updates')
  check(page.locator('.v15-boost').bounding_box()['y']+page.locator('.v15-boost').bounding_box()['height']<=page.locator('nav').bounding_box()['y'],'Manual keeps Boost completely above nav')
  page.screenshot(path=str(out/'v15_manual.png'))
  page.locator('.v15-boost').click()
  check(page.locator('#overlayFlowReadout').inner_text()=='350','Boost airflow shown on building')
  check(page.locator('#workspace').get_attribute('data-flow')=='boost','Boost distinct animation state')
  check(page.locator('#airFx').get_attribute('class').find('boost-surge')>=0,'Boost activation surge active')
  check('Stop Boost' in page.locator('.v15-boost').inner_text(),'Boost stop control distinct')
  page.screenshot(path=str(out/'v15_boost.png'))
  page.locator('.v15-boost').click()
  page.locator('nav [data-page="energy"]').click()
  check(page.locator('.v15-energy-hud').is_visible(),'Power reading moved to house')
  check(page.locator('.energy-v15 .measure-hero').count()==0,'No redundant large power number in dock')
  check('kW' in page.locator('.v15-energy-hud .v15-hud-value').inner_text(),'Power unit shown')
  check(page.locator('.v15-energy-status > span').count()==2,'Heating and water summaries on house')
  check(page.locator('.v15-energy-distribution i').count()==4,'Mini energy-flow strip shows independent loads')
  check(page.locator('.energy-v15 .v15-control-switch').count()==3,'Heating, water and valve have large controls')
  check(all(btn.bounding_box()['height']>=43 for btn in page.locator('.energy-v15 .v15-control-switch').all()),'Energy switches have 43px touch targets')
  check(outside(page.locator('.v15-energy-hud').bounding_box(),page.locator('#healthChip').bounding_box()),'Energy HUD avoids health')
  check(outside(page.locator('.v15-energy-hud').bounding_box(),page.locator('.energy-v15').bounding_box()),'Energy HUD avoids control dock')
  check(page.locator('.v15-health-link').bounding_box()['y']+page.locator('.v15-health-link').bounding_box()['height']<=page.locator('nav').bounding_box()['y'],'Energy health action fits above nav')
  page.screenshot(path=str(out/'v15_energy.png'))
  page.locator('.energy-v15 [data-action="toggleHeat"]').click()
  check('Off' in page.locator('.v15-heat').inner_text(),'Heating status updates on house')
  page.locator('.energy-v15 [data-action="toggleWater"]').click()
  check('Off' in page.locator('.v15-water').inner_text(),'Hot-water status updates on house')
  check('on' not in page.locator('#waterFx').get_attribute('class').split(),'Hot-water circuit turns off independently')
  page.locator('.energy-v15 [data-action="toggleWater"]').click()
  page.locator('.energy-v15 [data-action="waterValveConfirm"]').click()
  check(page.locator('#modalBack').is_visible(),'Water shutoff requires confirmation')
  page.locator('#dialogYes').click()
  check('Shut' in page.locator('.energy-v15 [data-action="waterValveConfirm"]').inner_text(),'Valve state updates')
  check('on' not in page.locator('#waterFx').get_attribute('class').split(),'Water circuit stops when valve shut')
  page.locator('.energy-v15 [data-action="waterValveConfirm"]').click()
  page.locator('#dialogYes').click()
  page.locator('.v15-health-link').click()
  check(page.locator('#modalBack').is_visible(),'Side Health action opens health dialog')
  page.locator('#modalBack [data-action="dismiss"]').last.click()
  page.locator('nav [data-page="more"]').click()
  page.locator('[data-tab="demo"]').click()
  page.locator('[data-action="leakTest"]').click()
  check(page.locator('#healthChip').get_attribute('data-level')=='critical','Leak critical alert preserved')
  page.locator('.demo-reset[data-action="clearFaults"]').click()
  page.locator('nav [data-page="climate"]').click()
  page.locator('.v15-hud-modes [data-mode="Eco"]').click()
  page.locator('nav [data-page="more"]').click()
  page.locator('[data-tab="demo"]').click()
  page.locator('[data-action="airTest"]').click()
  page.locator('nav [data-page="climate"]').click()
  check(page.locator('#overlayFlowReadout').inner_text()=='280','Air quality override updates house reading')
  check(page.locator('#workspace').get_attribute('data-flow')=='iaq','Air quality FX distinct')
  page.locator('.climate-v15 [data-action="toggleIaq"]').click()
  check(page.locator('#overlayFlowReadout').inner_text()=='110','Air quality auto off restores Eco flow')
  page.locator('nav [data-page="more"]').click()
  page.locator('[data-tab="demo"]').click()
  page.locator('.demo-reset[data-action="clearFaults"]').click()
  for tab in ['home','rooms','climate','energy','routines','more']:
    page.locator(f'nav [data-page="{tab}"]').click()
    check(page.locator('#workspace').get_attribute('data-page')==tab,f'{tab.title()} page renders')
    check(page.evaluate('document.documentElement.scrollHeight<=480 && document.documentElement.scrollWidth<=800'),f'{tab.title()} has no scroll')
  page.locator('nav [data-page="rooms"]').click()
  page.locator('.room-pick[data-room="bedroom"]').click()
  page.locator('[data-action="nextRoom"]').click()
  check(page.locator('.room-heading-row h2').inner_text()=='Living Room','Direct room cycling preserved')
  page.locator('nav [data-page="home"]').click()
  page.locator('.mode-choice[data-scene="Night"]').click()
  page.locator('[data-action="applyScene"]').click()
  check(page.locator('#modeSceneHint').inner_text()=='NIGHT · SOFT LIGHTING','Night appearance preserved')
  page.locator('.mode-choice[data-scene="Away"]').click()
  page.locator('[data-action="applyScene"]').click()
  check(page.locator('#modeSceneHint').inner_text()=='AWAY · LIGHTS OFF','Away appearance preserved')
  page.locator('#headerAlarm').click()
  page.locator('#dialogYes').click()
  check('Armed' in page.locator('#headerAlarm').inner_text(),'Alarm confirmation preserved')
  check(not errors,'No uncaught JavaScript errors: '+repr(errors))
  browser.close()
(out/'v15_test_results.json').write_text(json.dumps(checks,indent=2))
print('RESULT',sum(x['passed'] for x in checks),'/',len(checks))
if not all(x['passed'] for x in checks): raise SystemExit(1)
