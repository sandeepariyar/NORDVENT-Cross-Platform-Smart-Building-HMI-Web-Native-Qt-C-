from pathlib import Path
from playwright.sync_api import sync_playwright
from PIL import Image, ImageChops, ImageStat
import json
ROOT=Path(__file__).resolve().parent.parent
OUT=ROOT/'screenshots';OUT.mkdir(exist_ok=True)
checks=[]
def chk(condition, message):
    checks.append({'name':message,'passed':bool(condition)})
    print(('OK  ' if condition else 'FAIL'), message)
with sync_playwright() as p:
    browser=p.chromium.launch(headless=True,executable_path='/usr/bin/chromium',args=['--no-sandbox','--disable-dev-shm-usage'])
    page=browser.new_page(viewport={'width':800,'height':480}, device_scale_factor=1)
    errs=[];page.on('pageerror',lambda e:errs.append(str(e)))
    page.set_content((ROOT/'NORDVENT_Standalone.html').read_text(),wait_until='domcontentloaded',timeout=120000)
    page.wait_for_timeout(650)
    chk(page.locator('.mode-choice').count()==3,'Direct Home Night Away modes in header')
    chk(page.locator('.top #headerLock').count()==0 and page.locator('.top #headerAlarm').count()==0,'Lock/Alarm removed from header')
    chk(page.locator('.security-overlay #headerLock').is_visible() and page.locator('.security-overlay #headerAlarm').is_visible(),'Lock and Alarm float over house')
    chk(page.locator('.security-overlay').evaluate('e=>{const r=e.getBoundingClientRect();return r.y>=45&&r.right<=801&&r.left>=228}'),'Security controls remain over building on 800x480')
    chk(page.locator('.mode-choice[data-scene="Home"]').get_attribute('class').find('active')>=0,'Home default mode active')
    chk(float(page.locator('#fixture-living_ceiling').evaluate('e=>getComputedStyle(e).opacity'))>0.9,'Living light ON by default')
    chk(float(page.locator('#fixture-kitchen_pendants').evaluate('e=>getComputedStyle(e).opacity'))>0.9,'Kitchen light ON by default')
    chk(float(page.locator('#fixture-bedroom_ceiling').evaluate('e=>getComputedStyle(e).opacity'))<0.1,'Bedroom light OFF by default')
    chk(float(page.locator('#blind-bedroom').get_attribute('width'))==0,'Bedroom blinds open by default')
    chk(float(page.locator('#blind-living').get_attribute('width'))==0,'Living blinds open by default')
    page.screenshot(path=str(OUT/'v13_4_home.png'))
    # Night
    page.locator('.mode-choice[data-scene="Night"]').click()
    chk(page.locator('#modalBack').is_visible(),'Night confirmation opens')
    page.locator('button[data-action="applyScene"]').click()
    chk(page.locator('.mode-choice[data-scene="Night"]').get_attribute('class').find('active')>=0,'Night selected')
    chk(page.locator('#modeSceneHint').inner_text()=='NIGHT · SOFT LIGHTING','Night state badge')
    page.wait_for_timeout(550)
    night_levels={r:float(page.locator(f'#fixture-{r}').evaluate('e=>getComputedStyle(e).opacity')) for r in ['bedroom_ceiling','living_ceiling','kitchen_pendants']}
    chk(night_levels['bedroom_ceiling']>.5 and night_levels['living_ceiling']>.2 and night_levels['kitchen_pendants']<.01,'Night shows warm bedroom + living lighting')
    chk(float(page.locator('#blind-living').get_attribute('width'))>0,'Night partially closes living blinds')
    page.wait_for_timeout(650)
    page.locator('#toast').evaluate('e=>e.classList.remove("show")')
    page.screenshot(path=str(OUT/'v13_4_night.png'))
    # Away
    page.locator('.mode-choice[data-scene="Away"]').click()
    chk(page.locator('#modalBack').is_visible(),'Away confirmation opens')
    page.locator('button[data-action="applyScene"]').click()
    chk(page.locator('.mode-choice[data-scene="Away"]').get_attribute('class').find('active')>=0,'Away selected')
    chk(page.locator('#modeSceneHint').inner_text()=='AWAY · LIGHTS OFF','Away state badge')
    page.wait_for_timeout(550)
    chk(all(float(page.locator(f'#fixture-{r}').evaluate('e=>getComputedStyle(e).opacity'))<.01 for r in ['bedroom_ceiling','living_ceiling','kitchen_pendants']),'Away turns all interior lights off')
    chk(float(page.locator('#shade-bedroom').evaluate('e=>getComputedStyle(e).opacity'))>.7,'Away room shadows visibly darker')
    chk(all(float(page.locator(f'#blind-{r}').get_attribute('width'))>100 for r in ['bedroom','living','kitchen']),'Away closes all blinds')
    page.wait_for_timeout(650)
    page.locator('#toast').evaluate('e=>e.classList.remove("show")')
    page.screenshot(path=str(OUT/'v13_4_away.png'))
    # Lock/Alarm clicks test with new position
    page.locator('#headerLock').click()
    chk(page.locator('#modalBack').is_visible(),'Floating lock opens confirmation')
    page.locator('#dialogYes').click()
    chk('Unlocked' in page.locator('#headerLock').inner_text(),'Floating lock updates status')
    page.locator('#headerAlarm').click()
    chk(page.locator('#modalBack').is_visible(),'Floating alarm opens confirmation')
    page.locator('#dialogYes').click()
    chk('Armed' in page.locator('#headerAlarm').inner_text(),'Floating alarm updates status')
    # Room switching without exiting; verify left panel
    page.locator('[data-page="rooms"]').click()
    page.locator('.room-pick[data-room="bedroom"]').click()
    chk(page.locator('.room-side').is_visible(),'Room controls visible at left')
    page.locator('[data-action="nextRoom"]').click()
    chk(page.locator('.room-side h2').inner_text()=='Living Room','Next arrow switches room')
    page.locator('.room-mini-nav [data-room="kitchen"]').click()
    chk(page.locator('.room-side h2').inner_text()=='Kitchen','Room tile switches directly')
    page.locator('[data-action="prevRoom"]').click()
    chk(page.locator('.room-side h2').inner_text()=='Living Room','Previous arrow switches room')
    chk(not errs,'No uncaught JavaScript errors: '+repr(errs))
    browser.close()
(OUT/'v13_4_checks.json').write_text(json.dumps(checks,indent=2))
print('RESULT',sum(c['passed'] for c in checks),'/',len(checks))
if not all(c['passed'] for c in checks):raise SystemExit(1)
