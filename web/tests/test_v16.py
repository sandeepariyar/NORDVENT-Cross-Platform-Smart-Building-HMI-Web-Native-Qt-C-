"""Focused regression for v16 icon-only global status, keyboard and transitions."""
from pathlib import Path
from playwright.sync_api import sync_playwright
import json
root=Path(__file__).resolve().parents[1]
html=(root/'NORDVENT_Standalone.html').read_text()
shots=root/'screenshots';shots.mkdir(exist_ok=True)
checks=[]
def check(ok,desc):
    checks.append((bool(ok),desc))
    print(('PASS' if ok else 'FAIL'),desc)
with sync_playwright() as p:
    browser=p.chromium.launch(headless=True,executable_path='/usr/bin/chromium',args=['--no-sandbox','--disable-dev-shm-usage'])
    page=browser.new_page(viewport={'width':800,'height':480},device_scale_factor=1)
    errors=[];page.on('pageerror',lambda e:errors.append(str(e)))
    page.set_content(html,wait_until='domcontentloaded',timeout=120000)
    page.wait_for_timeout(350)
    dock=page.locator('.nv16-status-dock')
    check(dock.is_visible(),'Status dock visible on building')
    check(dock.locator('button').count()==3,'Exactly 3 icon-only status controls')
    check(all(b.bounding_box()['width']>=44 and b.bounding_box()['height']>=44 for b in dock.locator('button').all()),'44x44 touch targets')
    check(all(b.locator('.ico').is_visible() for b in dock.locator('button').all()),'All status glyphs visible')
    check(all(b.locator('.nv16-visually-hidden').count()==1 for b in dock.locator('button').all()),'No persistent visible text labels')
    check(all(b.get_attribute('aria-label') for b in dock.locator('button').all()),'Accessible icon labels')
    check(page.locator('#headerLock').get_attribute('aria-label').startswith('Door locked'),'Lock starts locked')
    check(page.locator('#headerAlarm').get_attribute('aria-label').startswith('Alarm disarmed'),'Alarm starts disarmed')
    check(page.locator('#healthChip').get_attribute('data-level')=='ok','Health initially healthy')
    check('rgba(' in page.locator('.home-panel').evaluate('(e)=>getComputedStyle(e).backgroundImage'),'Home uses translucent panel gradient')
    page.evaluate('document.getElementById("toast").classList.remove("show")')
    page.screenshot(path=str(shots/'v16_home.png'))
    # Click security controls: keep confirmation flow
    page.locator('#headerLock').click();check(page.locator('#modalBack').is_visible(),'Lock retains confirmation dialog')
    page.locator('#dialogYes').click()
    check(page.locator('#headerLock').get_attribute('aria-label').startswith('Door unlocked'),'Unlock changes glyph state')
    check(page.locator('#headerLock use').get_attribute('href')=='#i-nv-unlock','Unlocked icon shown')
    page.locator('#headerAlarm').click();check(page.locator('#modalBack').is_visible(),'Alarm retains confirmation dialog')
    page.locator('#dialogYes').click()
    check(page.locator('#headerAlarm').get_attribute('aria-label').startswith('Alarm armed'),'Alarm armed state reflected')
    page.locator('#headerAlarm').click();page.locator('#dialogYes').click()
    page.locator('#headerLock').click();page.locator('#dialogYes').click()
    # Health popover from icon
    page.locator('#healthChip').click();check(page.locator('#modalBack').is_visible(),'Health icon opens existing popup')
    page.locator('#modalBack [data-action="dismiss"]').last.click()
    page.locator('nav [data-page="climate"]').click()
    check(page.locator('.climate-v15').is_visible(),'Climate panel preserved')
    check(page.locator('#view > .nv16-enter').count()>=1,'Panel receives entrance class on page switch')
    check(page.locator('#healthChip').is_visible(),'Status dock persists on Climate')
    page.wait_for_timeout(250)
    page.evaluate('document.getElementById("toast").classList.remove("show")')
    page.screenshot(path=str(shots/'v16_climate.png'))
    page.locator('nav [data-page="energy"]').click()
    check(page.locator('.energy-v15').is_visible(),'Energy panel preserved')
    check(page.locator('#view > .nv16-enter').count()>=1,'Energy panel transitions in')
    page.wait_for_timeout(210)
    page.evaluate('document.getElementById("toast").classList.remove("show")')
    page.screenshot(path=str(shots/'v16_energy.png'))
    # Fault state: health icon turns red while tooltip/accessible name reflect the problem
    page.locator('nav [data-page="more"]').click()
    page.locator('[data-tab="demo"]').click()
    page.locator('[data-action="leakTest"]').click()
    check(page.locator('#healthChip').get_attribute('data-level')=='critical','Critical fault changes health icon to warning color')
    check('alert' in page.locator('#healthChip').get_attribute('aria-label'),'Critical event reflected in accessible name')
    page.locator('.demo-reset[data-action="clearFaults"]').click()
    check(page.locator('#healthChip').get_attribute('data-level')=='ok','Fault clear restores normal status')
    # Motion OFF should eliminate entry animation
    page.locator('[data-tab="display"]').click()
    page.locator('[data-action="toggleMotion"]').click()
    page.locator('nav [data-page="home"]').click()
    check(page.locator('#view > .nv16-enter').count()==0,'Motion OFF suppresses page animation')
    for k in ['home','rooms','climate','energy','routines','more']:
        page.locator(f'nav [data-page="{k}"]').click()
        check(not page.evaluate('document.documentElement.scrollHeight>480||document.documentElement.scrollWidth>800'),k+' stays no-scroll')
    check(not errors,'No uncaught JS errors')
    page.close()
    # Small-viewport scaled fit
    small=browser.new_page(viewport={'width':400,'height':240})
    small.set_content(html,wait_until='domcontentloaded',timeout=120000)
    small.wait_for_timeout(160)
    check(small.locator('#headerLock').is_visible() and small.locator('#healthChip').is_visible(),'Icon dock visible when scaled to 400x240')
    small.close();browser.close()
passed=sum(p for p,_ in checks)
(root/'test_v16_results.json').write_text(json.dumps({'passed':passed,'total':len(checks),'checks':[{'name':d,'passed':ok} for ok,d in checks]},indent=2))
print(f'RESULT {passed}/{len(checks)}')
if passed!=len(checks):raise SystemExit(1)
